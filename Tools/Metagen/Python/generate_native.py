"""Independent C++ and RTTR consumers of normalized Metagen schemas."""
import json
from pathlib import Path

from portable_schema import fingerprint
from format_generated import format_cpp

TYPES = {"boolean": "bool", "int32": "std::int32_t", "uint32": "std::uint32_t",
         "float32": "float", "float64": "double", "string": "std::string"}


def quoted(text):
    return json.dumps(text, ensure_ascii=False)


def literal(value, kind, boxed=False):
    if value is None:
        return "ice::meta::value{}" if boxed else "std::nullopt"
    if kind == "boolean":
        return "true" if value else "false"
    if kind == "string":
        return "std::string(" + quoted(value) + ")"
    if kind == "int32":
        return f"std::{'int64' if boxed else 'int32'}_t({value})"
    if kind == "uint32":
        return f"std::{'uint64' if boxed else 'uint32'}_t({value})"
    if kind == "float32" and not boxed:
        return f"static_cast<float>({value!r})"
    return repr(float(value))


def box(expression, kind, nullable):
    inner = f"*{expression}" if nullable else expression
    target = {"int32": "std::int64_t", "uint32": "std::uint64_t",
              "float32": "double", "float64": "double"}.get(kind)
    content = f"static_cast<{target}>({inner})" if target else inner
    result = f"ice::meta::value{{{content}}}"
    return f"({expression} ? {result} : ice::meta::value{{}})" if nullable else result


def tag_map(values):
    entries = ", ".join("{" + quoted(key) + ", " + quoted(value) + "}" for key, value in values.items())
    return "std::map<std::string, std::string>{" + entries + "}"


def generate(schemas, output):
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    digest = fingerprint(schemas)
    lines = ["// Generated by Tools/Metagen/check.py; do not edit.",
             f"// Portable schema SHA-256: {digest}", "#pragma once", '#include "ice/meta/schema.h"',
             "namespace ice::generated {"]
    registrations = ["// Generated RTTR consumer; do not edit.", '#include "schema.generated.h"',
                     "#include <rttr/registration>", "RTTR_REGISTRATION {", "using namespace rttr;"]
    for schema in schemas:
        name = schema["name"]
        lines += [f"/// Native projection of {schema['id']}; memory layout is not its wire format.", f"struct {name} {{"]
        for field in schema["fields"]:
            kind, nullable = field["type"]["kind"], field["type"]["nullable"]
            native = TYPES[kind]
            if nullable:
                native = f"std::optional<{native}>"
            initial = literal(field["default"], kind) if field["has_default"] else "{}"
            lines += [f"/// Stable field ID {field['id']}; native type {kind}.",
                      f"{native} {field['name']} = {initial};"]
        lines += ["};", f"/// Borrow immutable generated descriptors for {schema['id']}.",
                  f"inline const ice::meta::schema_descriptor &{name}_schema() {{",
                  "static const ice::meta::schema_descriptor schema = [] {", "ice::meta::schema_descriptor result;",
                  f"result.id = {quoted(schema['id'])};", f"result.version = {schema['version']};",
                  f"result.name = {quoted(name)};"]
        for key, val in schema["tags"].items():
            lines.append(f"result.tags.emplace({quoted(key)}, {quoted(val)});")
        for field in schema["fields"]:
            kind = field["type"]["kind"]
            lines += ["{ ice::meta::field_descriptor field;", f"field.id = {field['id']};",
                      f"field.name = {quoted(field['name'])};", f"field.kind = ice::meta::scalar_kind::{kind};",
                      f"field.nullable = {str(field['type']['nullable']).lower()};",
                      f"field.has_default = {str(field['has_default']).lower()};"]
            if field["has_default"]:
                lines.append(f"field.default_value = {literal(field['default'], kind, True)};")
            for bound in ("minimum", "maximum"):
                if field[bound] is not None:
                    lines.append(f"field.{bound} = {field[bound]!r};")
            for key, val in field["tags"].items():
                lines.append(f"field.tags.emplace({quoted(key)}, {quoted(val)});")
            lines += ["result.fields.push_back(std::move(field)); }"]
        lines += ["return result; }();", "return schema;", "}",
                  "/// Copy native state into portable values; validate before persistence or activation.",
                  f"inline ice::meta::record to_record(const {name} &object) {{", "return {"]
        for field in schema["fields"]:
            lines.append(f"{{{field['id']}, {box('object.'+field['name'], field['type']['kind'], field['type']['nullable'])}}},")
        lines += ["};", "}", "/// Validate a complete portable record before constructing native state.",
                  f"inline ice::expected<{name}, ice::meta::diagnostic> {name}_from_record(const ice::meta::record &input) {{",
                  f"auto checked = ice::meta::validate({name}_schema(), input);",
                  "if (!checked) return ice::unexpected(checked.error());", f"{name} result;"]
        for field in schema["fields"]:
            kind = field["type"]["kind"]
            getter = {"boolean": "bool", "int32": "std::int64_t", "uint32": "std::uint64_t",
                      "float32": "double", "float64": "double", "string": "std::string"}[kind]
            expression = f"std::get<{getter}>(checked->at({field['id']}))"
            if getter != TYPES[kind]:
                expression = f"static_cast<{TYPES[kind]}>({expression})"
            if field["type"]["nullable"]:
                lines.append(f"if (!std::holds_alternative<std::monostate>(checked->at({field['id']})))")
            lines.append(f"result.{field['name']} = {expression};")
        lines += ["return result;", "}"]
        registrations += [f"registration::class_<ice::generated::{name}>({quoted(schema['id'])})"]
        metadata = [f'metadata("metagen.type_id", std::string({quoted(schema["id"])}))',
                    f'metadata("metagen.version", std::uint32_t({schema["version"]}))',
                    f'metadata("metagen.native_name", std::string({quoted(schema["name"])}))',
                    f'metadata("metagen.tags", {tag_map(schema["tags"])})']
        metadata += [f'metadata({quoted(key)}, std::string({quoted(val)}))' for key, val in schema["tags"].items()]
        registrations += ["(" + ",\n".join(metadata) + ")", ".constructor<>()(policy::ctor::as_object)"]
        for field in schema["fields"]:
            registrations.append(f".property({quoted(field['name'])}, &ice::generated::{name}::{field['name']})")
            metadata = [f'metadata("metagen.field_id", std::uint32_t({field["id"]}))',
                        f'metadata("metagen.kind", std::string({quoted(field["type"]["kind"])}))',
                        f'metadata("metagen.nullable", {str(field["type"]["nullable"]).lower()})',
                        f'metadata("metagen.has_default", {str(field["has_default"]).lower()})',
                        f'metadata("metagen.tags", {tag_map(field["tags"])})']
            if field["has_default"]:
                metadata.append(f'metadata("metagen.default", ice::meta::value{{{literal(field["default"], field["type"]["kind"], True)}}})')
            for bound in ("minimum", "maximum"):
                if field[bound] is not None:
                    metadata.append(f'metadata("metagen.{bound}", {field[bound]!r})')
            metadata += [f'metadata({quoted(key)}, std::string({quoted(val)}))' for key, val in field["tags"].items()]
            registrations.append("(" + ",\n".join(metadata) + ")")
        registrations.append(";")
    lines.append("} // namespace ice::generated")
    registrations.append("}")
    (output / "schema.generated.h").write_text("\n".join(lines) + "\n")
    (output / "rttr.generated.cpp").write_text("\n".join(registrations) + "\n")

    # Generated C++ is reviewable source and follows the same pinned style as authored code.
    format_cpp([output / "schema.generated.h", output / "rttr.generated.cpp"])
