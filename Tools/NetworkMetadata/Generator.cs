using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Encodings.Web;
using Metagen;
namespace Ice.NetworkMetadata;

public sealed class NetworkGenerator : IMetaGenerator {
    public string Id => "ice.network.scalar";
    private static string Quote(string value) => JsonSerializer.Serialize(value,
        new JsonSerializerOptions { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping });
    private static string Number(double value) => value.ToString("R", CultureInfo.InvariantCulture);
    private static string NativeName(NetworkType type) => "record_" + type.Id.Replace('.', '_');
    private static string NativeType(NetworkField field) => field.LogicalType switch {
        "float32" => "float", "uint32" => "std::uint32_t", "entity_reference" => "entity_reference",
        _ => throw new InvalidDataException("Unknown projected native type")
    };
    public GenerationResult Generate(IMetaSource source) {
        try {
            var policies = NetworkPolicy.Read(source);
            // Native names derive from stable IDs, never presentation names or declaration order.
            if (policies.Any(p => NativeName(p).Contains("__", StringComparison.Ordinal)) ||
                policies.Select(NativeName).Distinct(StringComparer.Ordinal).Count() != policies.Count)
                throw new InvalidDataException("Stable IDs collide as native identifiers");
            var types = new StringBuilder("// Generated by ice.network.scalar/1. Do not edit.\n#pragma once\n#include \"runtime.h\"\nnamespace ice::network_proof {\n");
            var codecs = new StringBuilder("// Generated by ice.network.scalar/1. Do not edit.\n#pragma once\n#include \"network.types.generated.h\"\nnamespace ice::network_proof {\n");
            foreach (var type in policies) {
                var name = NativeName(type);
                types.AppendLine($"/// Typed record for stable schema {type.Id}, version {type.Version}.");
                types.AppendLine($"struct {name} {{");
                foreach (var field in type.Fields) {
                    types.AppendLine($"\t/// Stable field {field.Id}; presentation metadata is in its descriptor.");
                    types.AppendLine($"\t{NativeType(field)} f{field.Id}{{}};");
                }
                types.AppendLine($"\tbool operator==(const {name} &) const = default;\n}};");
                codecs.AppendLine($"inline constexpr std::array<field_descriptor, {type.Fields.Count}> {name}_fields{{{{");
                foreach (var field in type.Fields)
                    codecs.AppendLine($"\t{{{field.Id}, {Quote(field.Name)}, wire_codec::{field.Codec}, {field.CodecVersion}, {Number(field.Minimum ?? 0)}, {Number(field.Maximum ?? 0)}, {Quote(field.Unit)}, {Quote(field.Interpolation)}, {Quote(field.Reference)}}},");
                codecs.AppendLine("}};");
                var fingerprint = string.Join(", ", Enumerable.Range(0, 32).Select(i => "0x" + type.Fingerprint.Substring(i * 2, 2)));
                codecs.AppendLine($"inline constexpr type_descriptor {name}_descriptor{{\n\t{Quote(type.Id)}, {Quote(type.Name)}, {type.Version}, {{{fingerprint}}},\n\t{Quote(type.Writer)}, {Quote(type.Audience)}, {Quote(type.Delivery)}, {Quote(type.Conflict)}, {Quote(type.Direction)}, {Quote(type.Capability)}, {Quote(type.Deduplication)}, {name}_fields\n}};");
                codecs.AppendLine($"/// Metadata for stable schema {type.Id}.\ninline constexpr const type_descriptor &descriptor(const {name} *) {{ return {name}_descriptor; }}");
                foreach (var qualifier in new[] { "", "const " }) {
                    codecs.AppendLine($"/// Traverse generated fields in stable field-ID order.\ntemplate <class F> bool visit_fields({qualifier}{name} &value, F &&visit) {{");
                    codecs.Append("\treturn ");
                    codecs.Append(string.Join(" &&\n\t       ", type.Fields.Select((f, index) => $"visit({name}_fields[{index}], value.f{f.Id})")));
                    codecs.AppendLine(";\n}");
                }
                if (type.Direction.Length != 0) {
                    codecs.AppendLine($"/// Validate and dispatch against current authenticated host context; no client payload grants authority.\ninline status validate_and_dispatch(const {name} &value, event_host &host, sequence_window &window) {{");
                    codecs.AppendLine("\tstd::vector<detail::encoded_field> checked;\n\tif (!detail::collect(value, checked)) return status::invalid_value;");
                    codecs.AppendLine($"\treturn dispatch_fire(value.f1, value.f2, {{value.f3, value.f4, value.f5}}, {Quote(type.Capability)}, host, window);\n}}");
                }
            }
            types.AppendLine("} // namespace ice::network_proof");
            codecs.AppendLine($"/// Generated discovery enumerates exactly the descriptors used by native validation.\ninline constexpr std::array<const type_descriptor *, {policies.Count}> network_types{{{{");
            foreach (var type in policies) codecs.AppendLine($"\t&{NativeName(type)}_descriptor,");
            codecs.AppendLine("}};\n} // namespace ice::network_proof");
            var discovery = new { profile = NetworkPolicy.Profile, domains = new[] { "authority", "presentation" },
                host_requirements = new[] { "authenticated_principal", "current_room_epoch", "weapon_resolution_ownership",
                    "weapon.fire_capability", "unit_aim", "authority_cooldown", "principal_epoch_sequence_window" },
                transport = "not_implemented", types = policies };
            GeneratedArtifact Artifact(string path, string mediaType, string content) => new(path, mediaType, Encoding.UTF8.GetBytes(content));
            return new GenerationResult(new[] {
                Artifact("network.types.generated.h", "text/x-c++hdr", types.ToString()),
                Artifact("network.generated.h", "text/x-c++hdr", codecs.ToString()),
                Artifact("network.discovery.generated.json", "application/json", JsonSerializer.Serialize(discovery, NetworkPolicy.Json) + "\n"),
                Artifact("network.policy.generated.json", "application/json", JsonSerializer.Serialize(policies, NetworkPolicy.Json) + "\n")
            }, Array.Empty<MetaDiagnostic>());
        } catch (Exception error) when (error is InvalidDataException or InvalidOperationException or OverflowException or ArgumentException or IndexOutOfRangeException or FormatException or InvalidCastException or KeyNotFoundException) {
            return new GenerationResult(Array.Empty<GeneratedArtifact>(), new[] {
                new MetaDiagnostic(DiagnosticSeverity.Error, "ice.net.invalid", error.Message)
            });
        }
    }
}
